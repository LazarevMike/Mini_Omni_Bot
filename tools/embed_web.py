"""Packs web/ into firmware/OmniBots_Mini/web_assets.h so that the robot can serve the page.

The packed file is kept in the repository, so building the robot does not require Python.
PlatformIO packs it again before every build (extra_scripts in platformio.ini). After a
change in web/ when using the Arduino IDE, run this script by hand and commit the result:

    python3 tools/embed_web.py

`python3 tools/embed_web.py --check` only checks that the packed file is up to date.

Text files are gzipped; the robot sends them with Content-Encoding: gzip.
The output changes only when web/ changes, so it does not trigger rebuilds.
"""

import gzip
from pathlib import Path

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript",
    ".css": "text/css",
    ".json": "application/manifest+json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
}
COMPRESS = {".html", ".js", ".css", ".json", ".svg"}
CACHE = {".png"}  # icons rarely change; the rest is re-checked on every load


def render(root: Path):
    web = root / "web"
    out = root / "firmware" / "OmniBots_Mini" / "web_assets.h"
    files = sorted(p for p in web.rglob("*") if p.is_file() and not p.name.startswith("."))
    lines = [
        "// Generated by tools/embed_web.py from web/ - do not edit.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct WebAsset {",
        "  const char *path;",
        "  const char *type;",
        "  const uint8_t *data;",
        "  size_t size;",
        "  bool gzip;",
        "  bool cache;",
        "};",
        "",
    ]
    table = []
    for i, path in enumerate(files):
        if path.suffix not in TYPES:
            raise SystemExit(f"embed_web.py: no content type for {path}")
        rel = path.relative_to(web).as_posix()
        url = "/" if rel == "index.html" else "/static/" + rel
        data = path.read_bytes()
        zipped = path.suffix in COMPRESS
        if zipped:
            data = gzip.compress(data, compresslevel=9, mtime=0)
        lines.append(f"// {rel}")
        lines.append(f"static const uint8_t WEB_ASSET_{i}[] = {{")
        for start in range(0, len(data), 20):
            lines.append("  " + ",".join(str(b) for b in data[start : start + 20]) + ",")
        lines.append("};")
        table.append(
            f'  {{"{url}", "{TYPES[path.suffix]}", WEB_ASSET_{i}, sizeof WEB_ASSET_{i}, '
            f'{"true" if zipped else "false"}, {"true" if path.suffix in CACHE else "false"}}},'
        )
    lines += ["", "static const WebAsset WEB_ASSETS[] = {", *table, "};"]
    lines.append("static const size_t WEB_ASSET_COUNT = sizeof WEB_ASSETS / sizeof WEB_ASSETS[0];")
    return out, "\n".join(lines) + "\n"


def build(root: Path) -> Path:
    out, text = render(root)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out


def check(root: Path) -> bool:
    """True if the packed page in the repo matches web/ (the host test runs this)."""
    out, text = render(root)
    return out.exists() and out.read_text() == text


try:
    Import("env")  # noqa: F821 - defined when PlatformIO runs this as an extra script
    build(Path(env.subst("$PROJECT_DIR")))  # noqa: F821
except NameError:
    import sys

    ROOT = Path(__file__).resolve().parent.parent
    if "--check" in sys.argv:
        if not check(ROOT):
            sys.exit("web_assets.h is out of date: run `python3 tools/embed_web.py` and commit it")
        print("web_assets.h matches web/")
    else:
        print(build(ROOT))
